import { assert, test } from 'orca/testing'
import { build, LIMITS, parseLines, slim, toolSummary } from './transcript.ts'
import { HIDDEN } from './redact.ts'
import { apiRequest, assistant, basicSession, iso, jsonl, prompt, T0, toolResult, toolUse } from './fixtures.ts'

const LATER = T0 + 24 * 3600_000 // long after: nothing is under way

test('a prompt, a request with a tool call, and the answer', () => {
  const t = build(parseLines(jsonl(basicSession())), [], true, LATER)
  assert.equal(t.turns.length, 1)
  const turn = t.turns[0]
  assert.equal(turn.prompt, 'Read the parser and fix it')
  assert.equal(turn.steps.length, 2)
  const [a, b] = turn.steps
  // Sent when the api-request was written; first and last blocks from the replies.
  assert.equal(a.at, T0 + 100)
  assert.equal(a.firstAt, T0 + 900)
  assert.equal(a.endedAt, T0 + 1000)
  assert.equal(a.input, 20002)
  assert.equal(a.output, 80)
  assert.equal(a.stopReason, 'tool_use')
  assert.equal(a.text, 'Reading it.')
  assert.equal(a.calls.length, 1)
  const c = a.calls[0]
  assert.equal(c.tool, 'Read')
  assert.equal(c.summary, 'parser.ts')
  assert.equal(c.ms, 400)
  assert.ok(c.done)
  assert.deepEqual(c.lines, ['line one', 'line two', 'line three'])
  // The second request grew by 500 - 80 = 420 tokens, all from the one result.
  assert.equal(c.tokens, 20502 - 20002 - 80)
  assert.equal(b.status, 'done')
  assert.equal(b.text, 'Fixed.')
  assert.equal(t.requests, 2)
  assert.equal(t.calls, 1)
  assert.equal(t.next, 20502 + 300)
  // The fixed overhead: the first input less the prompt's estimate.
  assert.equal(t.overhead, 20002 - Math.round('Read the parser and fix it'.length / 4))
  assert.equal(t.truncated, false)
})

test('no overhead from a transcript that starts midway', () => {
  const t = build(parseLines(jsonl(basicSession())), [], false, LATER)
  assert.equal(t.overhead, null)
  assert.equal(t.truncated, true)
})

test('a request still under way, and one sent with nothing back yet', () => {
  const lines = basicSession()
  const now = T0 + 5000
  const streaming = [...lines.slice(0, -1), assistant(3500, 'r2', [{ type: 'text', text: 'Fix' }], null, null, 'req-b')]
  const t1 = build(parseLines(jsonl(streaming)), [], true, now)
  assert.equal(t1.turns[0].steps.at(-1)!.status, 'streaming')
  const sent = [...lines.slice(0, -1)]
  const t2 = build(parseLines(jsonl(sent)), [], true, now)
  const last = t2.turns[0].steps.at(-1)!
  assert.equal(last.status, 'streaming')
  assert.equal(last.firstAt, null)
  assert.equal(last.at, T0 + 1500)
})

test('compaction is marked on the request after it', () => {
  const lines = [...basicSession(), { type: 'system', subtype: 'compact_boundary', timestamp: iso(4000) }, prompt(5000, 'next'), assistant(6000, 'r3', [{ type: 'text', text: 'ok' }])]
  const t = build(parseLines(jsonl(lines)), [], true, LATER)
  const s = t.turns.at(-1)!.steps[0]
  assert.ok(s.isCompacted)
})

test('slash commands read as typed; command output and meta lines are not prompts', () => {
  const lines = [
    prompt(0, '<command-name>/review</command-name>\n<command-args>src/a.ts</command-args>'),
    prompt(1, '<local-command-stdout>done</local-command-stdout>'),
    prompt(2, 'Caveat: The messages below were generated by the user while running local commands.'),
    prompt(3, 'injected context', { isMeta: true }),
    prompt(4, '<system-reminder>only a reminder</system-reminder>'),
    prompt(5, '[Request interrupted by user]')
  ]
  const recs = parseLines(jsonl(lines))
  assert.deepEqual(
    recs.map((r) => (r.k === 'prompt' ? r.text : r.k)),
    ['/review src/a.ts']
  )
})

test('secrets in prompts, inputs and results are masked', () => {
  const key = 'sk-ant-api03-abcdefghijklmnopqrstuvwxyz0123'
  const lines = [
    prompt(0, `use ${key}`),
    assistant(100, 'r1', [toolUse('toolu_9', 'Bash', { command: `curl -H "x-api-key: ${key}" https://api` })], undefined, 'tool_use'),
    toolResult(200, 'toolu_9', `{"key":"${key}"}`)
  ]
  const t = build(parseLines(jsonl(lines)), [], true, LATER)
  const json = JSON.stringify(t)
  assert.ok(!json.includes(key), 'the key leaked')
  assert.equal(t.turns[0].prompt, HIDDEN)
  const c = t.turns[0].steps[0].calls[0]
  assert.equal(c.summary, HIDDEN)
  assert.deepEqual(c.input, [['command', HIDDEN]])
  assert.deepEqual(c.lines, [HIDDEN])
})

test('malformed and hostile lines are skipped, not trusted', () => {
  const text = [
    'not json',
    '{"type":"assistant"',
    JSON.stringify({ type: 'assistant', timestamp: 'yesterday', requestId: 'r', message: { content: [] } }),
    JSON.stringify({ type: 'assistant', timestamp: iso(0), requestId: { x: 1 }, message: 'nope' }),
    JSON.stringify({ type: 'user', timestamp: iso(0), message: { content: [{ type: 'tool_result', tool_use_id: '../../etc', content: 'x' }] } }),
    // Strings where numbers belong, a tool name with spaces, an id that is too long.
    JSON.stringify(assistant(10, 'r9', [toolUse('a'.repeat(300), 'Read', {}), toolUse('ok_1', 'rm -rf', {})], { input_tokens: '9e9', output_tokens: -5 })),
    // Prototype keys in input stay plain data.
    `{"type":"assistant","timestamp":"${iso(20)}","requestId":"r10","message":{"content":[{"type":"tool_use","id":"toolu_p","name":"Edit","input":{"__proto__":{"polluted":true},"file_path":"/a/b.ts"}}],"usage":{"input_tokens":1,"output_tokens":1}}}`,
    JSON.stringify({ ...assistant(30, 'side', [{ type: 'text', text: 'sidechain' }]), isSidechain: true })
  ].join('\n')
  const recs = parseLines(text)
  const t = build(recs, [], true, LATER)
  assert.equal(({} as Record<string, unknown>).polluted, undefined)
  const steps = t.turns.flatMap((x) => x.steps)
  assert.equal(steps.length, 2)
  assert.equal(steps[0].input, 0)
  assert.equal(steps[0].output, 0)
  assert.equal(steps[0].calls.length, 0)
  assert.equal(steps[1].calls[0].summary, 'b.ts')
  assert.ok(!JSON.stringify(t).includes('sidechain'))
})

test('subagent calls hang under their Agent call', () => {
  const lines = [
    prompt(0, 'look around'),
    assistant(100, 'r1', [toolUse('toolu_ag', 'Agent', { description: 'Explore code', subagent_type: 'Explore', prompt: 'go' })], undefined, 'tool_use'),
    toolResult(5000, 'toolu_ag', 'found it')
  ]
  const sub = [
    assistant(200, 's1', [toolUse('toolu_s1', 'Grep', { pattern: 'parse' })], undefined, 'tool_use'),
    toolResult(400, 'toolu_s1', 'a.ts:1'),
    assistant(500, 's2', [toolUse('toolu_s2', 'Read', { file_path: '/x/a.ts' })], undefined, 'tool_use')
  ]
  const t = build(parseLines(jsonl(lines)), [{ toolUseId: 'toolu_ag', agentType: 'Explore', records: parseLines(jsonl(sub), { sidechain: true }) }], true, LATER)
  const c = t.turns[0].steps[0].calls[0]
  assert.equal(c.agentType, 'Explore')
  assert.equal(c.summary, 'Explore code')
  assert.deepEqual(
    c.sub.map((s) => [s.tool, s.summary, s.done]),
    [
      ['Grep', '"parse"', true],
      ['Read', 'a.ts', false]
    ]
  )
  assert.equal(t.calls, 3)
})

test('keeps only the newest requests', () => {
  const lines: unknown[] = [prompt(0, 'loop')]
  for (let i = 0; i < LIMITS.steps + 10; i++) lines.push(assistant(10 + i, `r${i}`, [{ type: 'text', text: `step ${i}` }]))
  const t = build(parseLines(jsonl(lines)), [], true, LATER)
  const steps = t.turns.flatMap((x) => x.steps)
  assert.equal(steps.length, LIMITS.steps)
  assert.equal(steps.at(-1)!.text, `step ${LIMITS.steps + 9}`)
  assert.equal(t.requests, LIMITS.steps + 10)
  assert.ok(t.truncated)
})

test('requests from other query sources are not taken as under way', () => {
  const lines = [...basicSession(), apiRequest(4000, 'req-title', 'generate_session_title')]
  const t = build(parseLines(jsonl(lines)), [], true, T0 + 5000)
  assert.equal(t.turns[0].steps.length, 2)
  assert.equal(t.turns[0].steps.at(-1)!.status, 'done')
})

test('tool summaries', () => {
  assert.equal(toolSummary('Bash', { command: 'cd /x && npm test' }), 'npm test')
  assert.equal(toolSummary('Grep', { pattern: 'foo' }), '"foo"')
  assert.equal(toolSummary('Write', { file_path: 'C:\\a\\b.txt' }), 'b.txt')
  assert.equal(toolSummary('Mystery', null), '')
  assert.equal(slim(null), null)
})
