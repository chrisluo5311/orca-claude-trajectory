const LATER = T0 + 24 * 3600_000 // long after: nothing is under way

test('a prompt, a request with a tool call, and the answer', () => {
  const t = build(parseLines(jsonl(basicSession())), [], true, LATER)
  assert.equal(t.turns.length, 1)
  const turn = t.turns[0]
  assert.equal(turn.prompt, 'Read the parser and fix it')
  assert.equal(turn.steps.length, 2)
  const [a, b] = turn.steps
  // Sent when the api-request was written; first and last blocks from the replies.
  assert.equal(a.at, T0 + 100)
  assert.equal(a.firstAt, T0 + 900)
  assert.equal(a.endedAt, T0 + 1000)
  assert.equal(a.input, 20002)
  assert.equal(a.output, 80)
  assert.equal(a.stopReason, 'tool_use')
  assert.equal(a.text, 'Reading it.')
  assert.equal(a.calls.length, 1)
  const c = a.calls[0]
  assert.equal(c.tool, 'Read')
  assert.equal(c.summary, 'parser.ts')
  assert.equal(c.ms, 400)
  assert.ok(c.done)
  assert.deepEqual(c.lines, ['line one', 'line two', 'line three'])
  // The second request grew by 500 - 80 = 420 tokens, all from the one result.
  assert.equal(c.tokens, 20502 - 20002 - 80)
  assert.equal(b.status, 'done')
  assert.equal(b.text, 'Fixed.')
  assert.equal(t.requests, 2)
  assert.equal(t.calls, 1)
  assert.equal(t.next, 20502 + 300)
  // The fixed overhead: the first input less the prompt's estimate.
  assert.equal(t.overhead, 20002 - Math.round('Read the parser and fix it'.length / 4))
  assert.equal(t.truncated, false)
})

test('no overhead from a transcript that starts midway', () => {
  const t = build(parseLines(jsonl(basicSession())), [], false, LATER)
  assert.equal(t.overhead, null)
  assert.equal(t.truncated, true)
})

test('a request still under way, and one sent with nothing back yet', () => {
  const lines = basicSession()
  const now = T0 + 5000
  const streaming = [...lines.slice(0, -1), assistant(3500, 'r2', [{ type: 'text', text: 'Fix' }], null, null, 'req-b')]
  const t1 = build(parseLines(jsonl(streaming)), [], true, now)
  assert.equal(t1.turns[0].steps.at(-1)!.status, 'streaming')
  const sent = [...lines.slice(0, -1)]
  const t2 = build(parseLines(jsonl(sent)), [], true, now)
  const last = t2.turns[0].steps.at(-1)!
  assert.equal(last.status, 'streaming')
  assert.equal(last.firstAt, null)
  assert.equal(last.at, T0 + 1500)
})

